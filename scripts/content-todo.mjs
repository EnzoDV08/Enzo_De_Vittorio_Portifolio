// Regenerates CONTENT_TODO.md from the todo("…") calls in app/content and from images that
// projects reference but don't have yet. Run: npm run todo
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "app/content";
const sections = [];

for (const file of readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "todo.ts")) {
  // Prettier may wrap long todo("…") calls over several lines; fold them back first.
  const src = readFileSync(join(dir, file), "utf8").replace(
    /todo\(\s*\n\s*("[^"]+"),?\s*\n\s*\)/g,
    "todo($1)",
  );
  const items = [];
  let slug = null;
  for (const line of src.split("\n")) {
    const s = line.match(/^\s*slug: "([^"]+)"/);
    if (s) slug = s[1];
    for (const m of line.matchAll(/todo\(\s*"([^"]+)"\s*\)/g)) {
      const key = line.match(/^\s*(?:\{\s*name: "([^"]+)",\s*)?(\w+):/);
      const where = [slug, key?.[1] ?? key?.[2]].filter(Boolean).join(" → ");
      items.push(`- [ ] ${m[1]} — \`${file}\`${where ? ` · ${where}` : ""}`);
    }
  }
  if (items.length) sections.push(`### ${file}\n\n${items.join("\n")}`);
}

// Images: every project cover and gallery path that doesn't exist on disk yet.
const projectsSrc = readFileSync(join(dir, "projects.ts"), "utf8");
const missing = [];
let current = null;
for (const line of projectsSrc.split("\n")) {
  const t = line.match(/^\s*title: "([^"]+)"/);
  if (t) current = t[1];
  const c = line.match(/^\s*(cover|src): "(projects\/[^"]+)"/);
  if (c && !existsSync(join("app/assets", c[2]))) {
    const spec = c[1] === "cover" ? "cover 2400×1500" : "gallery 1920×1200";
    missing.push(`- [ ] **${current}**, ${spec} → \`_originals/${c[2].replace("projects/", "")}\``);
  }
}

const out = `# Content TODO

Generated by \`npm run todo\` from \`todo()\` values in \`app/content/\` and from missing image files.
Don't edit by hand, fix the content, then re-run.

Every item shows as a visible "TODO(enzo)" marker on the site (or hides its link) until it's filled in.

## Content

${sections.join("\n\n")}

## Images

Drop full-size files in \`_originals/<slug>/\` (any of jpg/png/webp/heic), then run \`npm run images\`.
Until then each project shows a designed placeholder.

Specs: **cover 2400×1500** (16:10), **gallery 1920×1200**, **OG image 1200×630** (generated automatically from the cover, no action needed).

${missing.join("\n")}

The covers and galleries for Lente Book, Honeybee Heroes and MPG Foundation are
**automated screenshots of the live sites** (October 2026). They're real, but replace them with
designed mockups or screen recordings when you can.

- [ ] Optional: short muted cover loops (\`cover.mp4\`, ≤ 10 s, ≤ 2 MB) for featured projects

## Other

- [ ] Replace \`public/Enzo-De-Vittorio-CV.pdf\` with the 2026 CV
- [ ] Confirm the canonical site URL. It's set to \`https://myportfolio-8c863.web.app\` in \`site.ts\`; change it if you add a custom domain
- [ ] Confirm earlier-work years marked TODO, evidence and best guesses are in \`REDESIGN_NOTES.md\`
- [ ] Group-project collaborators are credited by GitHub handle (from each repo's contributor list). Replace with real names and roles
- [ ] Two links in the old site no longer resolve publicly: \`EnzoDV5/Escape_Today\` and \`EnzoDV08/ONE-RIVER-TWO-MEMORIES_FINAL\` both return 404 (private?). Kept as briefed, make them public or remove them
- [ ] Pendoring category for Leke Lente Lingo
- [ ] EmailJS: add \`VITE_EMAILJS_SERVICE_ID\`, \`VITE_EMAILJS_TEMPLATE_ID\`, \`VITE_EMAILJS_PUBLIC_KEY\` (local \`.env\` and GitHub Actions secrets). Without them the contact form stays hidden
`;

writeFileSync("CONTENT_TODO.md", out);
const count = (out.match(/- \[ \]/g) ?? []).length;
console.log(`CONTENT_TODO.md: ${count} open items`);
